import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { createBookingApi, openBookingDb, setAdminPassword } from '../booking-api.mjs';
import { createServer } from '../app-server.mjs';

const dir = mkdtempSync(join(process.cwd(), '.test-booking-'));
const path = join(dir, 'bookings.sqlite');
const db = openBookingDb(path);
const api = createBookingApi(db);
const day = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Bahia', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date(Date.now() + 3 * 86400000));
const weekday = new Date(`${day}T12:00:00Z`).getUTCDay();
const settings = api.settings();
settings.services[0].enabled = true;
settings.services[0].duration = 60;
settings.services[0].priceCents = 3000;
settings.services[0].photoUrl = './assets/corte-perfil-instagram.jpg';
settings.services[1].enabled = true;
settings.services[1].duration = 30;
settings.services[1].priceCents = 2000;
settings.services[1].photoUrl = './assets/destaque-barbas-02.jpg';
settings.hours[weekday] = { weekday, opens: '08:00', closes: '12:00', breakStart: '10:00', breakEnd: '10:30' };
api.updateSettings(settings);
assert.equal(api.publicConfig().services[0].priceCents, 3000);
assert.equal(api.agenda(day).find(x => x.time === '08:00').status, 'available');
assert.equal(api.agenda(day).find(x => x.time === '10:00').status, 'unavailable');
assert.equal(api.agenda(day).find(x => x.time === '11:30').status, 'available');
assert.equal(api.slots(day, settings.services[0].id).some(x => x.time === '11:30'), false, 'Serviço longo não cabe no fim do dia');
assert.equal(api.slots(day, settings.services[1].id).find(x => x.time === '11:30').status, 'available');
setAdminPassword(db, 'senha-forte-de-teste-123');
assert.equal(api.authenticated(api.login('senha-forte-de-teste-123')), true);
assert.throws(() => api.login('incorreta'), { status: 401 });
assert.equal(api.slots(day, settings.services[0].id).some(x => x.time === '09:30'), false, 'Serviço não pode atravessar o intervalo');
const input = { day, time: '08:00', serviceId: settings.services[0].id, name: 'Maria Silva', phone: '11999999999' };
const first = api.request(input);
assert.equal(first.status, 'pending');
assert.throws(() => api.request(input), { status: 409 }, 'Reserva duplicada deve falhar');
assert.throws(() => api.request({ ...input, time: '08:30', serviceId: settings.services[1].id }), { status: 409 }, 'Serviços de durações diferentes não podem sobrepor');
assert.equal(api.slots(day, settings.services[1].id).find(x => x.time === '08:00').status, 'pending');
assert.equal(api.agenda(day).find(x => x.time === '08:00').status, 'pending');
api.decide(first.id, 'confirm');
assert.equal(api.slots(day, settings.services[1].id).find(x => x.time === '08:00').status, 'confirmed');
api.decide(first.id, 'cancel');
assert.equal(api.slots(day, settings.services[1].id).find(x => x.time === '08:00').status, 'available');
const block = api.block(day, '08:00', 30);
assert.equal(api.slots(day, settings.services[1].id).find(x => x.time === '08:00').status, 'blocked');
api.unblock(block.id);
assert.equal(api.slots(day, settings.services[1].id).find(x => x.time === '08:00').status, 'available');
const expired = api.request(input);
db.prepare('UPDATE appointments SET expires_at=? WHERE id=?').run(Date.now() - 1, expired.id);
assert.equal(api.slots(day, settings.services[1].id).find(x => x.time === '08:00').status, 'available', 'Reserva expirada deve liberar horário');
assert.throws(() => api.decide(expired.id, 'confirm'), { status: 409 }, 'Reserva expirada não pode ser confirmada');
assert.throws(() => api.request({ ...input, time: '12:00' }), { status: 409 });
const expanded = api.settings();
expanded.services.push({ id: null, name: 'Novo serviço de teste', duration: 30, enabled: false, priceCents: null, photoUrl: null });
api.updateSettings(expanded);
assert.ok(api.settings().services.some(service => service.name === 'Novo serviço de teste'));
const specialDay = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Bahia', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date(Date.now() + 4 * 86400000));
const official = api.settings();
official.specialHours = [{ day: specialDay, opens: '08:00', closes: '17:00', breakStart: '12:00', breakEnd: '14:00' }];
api.updateSettings(official);
assert.equal(api.agenda(specialDay).find(x => x.time === '12:00').status, 'unavailable');
assert.deepEqual(['08:00', '11:30', '14:00', '16:30'].map(time => api.slots(specialDay, settings.services[1].id).find(x => x.time === time)?.status),
  ['available', 'available', 'available', 'available']);
assert.equal(api.slots(specialDay, settings.services[0].id).some(x => x.time === '11:30' || x.time === '16:30'), false);
for (const time of ['08:00', '11:30', '14:00', '16:30']) {
  const request = api.request({ ...input, day: specialDay, time, serviceId: settings.services[1].id });
  assert.equal(request.status, 'pending');
  api.decide(request.id, 'cancel');
}
assert.throws(() => api.request({ ...input, day: specialDay, time: '17:00', serviceId: settings.services[1].id }), { status: 409 });
const fineGrid = api.settings(); fineGrid.slotMinutes = 15; api.updateSettings(fineGrid);
assert.equal(api.agenda(specialDay).find(x => x.time === '08:15').status, 'available');
const coarseGrid = api.settings(); coarseGrid.slotMinutes = 60; api.updateSettings(coarseGrid);
assert.equal(api.agenda(specialDay).some(x => x.time === '08:30'), false);
assert.throws(() => api.request({ ...input, day: specialDay, time: '08:30', serviceId: settings.services[1].id }), { status: 400 });
const defaultGrid = api.settings(); defaultGrid.slotMinutes = 30; api.updateSettings(defaultGrid);
db.close();
const reopened = openBookingDb(path);
assert.equal(createBookingApi(reopened).appointments(day, day).length, 3, 'Dados devem persistir após reabrir SQLite');
reopened.close();

const server = createServer(path);
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
try {
  const [a, b] = await Promise.all([0, 1].map(() => fetch(`${base}/api/public/appointments`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(input) })));
  assert.deepEqual([a.status, b.status].sort(), [201, 409], 'Duas solicitações simultâneas não podem reservar o mesmo horário');
  const requested = await (a.status === 201 ? a : b).json();
  const unauthorized = await fetch(`${base}/api/admin/settings`);
  assert.equal(unauthorized.status, 401);
  const login = await fetch(`${base}/api/admin/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ password: 'senha-forte-de-teste-123' }) });
  assert.equal(login.status, 200);
  const session = login.headers.get('set-cookie').split(';')[0];
  const authorized = await fetch(`${base}/api/admin/settings`, { headers: { Cookie: session } });
  assert.equal(authorized.status, 200);
  const confirm = await fetch(`${base}/api/admin/appointments/${requested.id}/confirm`, { method: 'POST', headers: { Cookie: session, 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(confirm.status, 200);
  const agenda = await fetch(`${base}/api/admin/appointments?from=${day}&to=${day}`, { headers: { Cookie: session } });
  assert.equal((await agenda.json()).appointments.find(item => item.id === requested.id).status, 'confirmed');
  const cancel = await fetch(`${base}/api/admin/appointments/${requested.id}/cancel`, { method: 'POST', headers: { Cookie: session, 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(cancel.status, 200);
  const blocked = await fetch(`${base}/api/admin/blocks`, { method: 'POST', headers: { Cookie: session, 'Content-Type': 'application/json' }, body: JSON.stringify({ day, time: '08:00', duration: 30 }) });
  assert.equal(blocked.status, 201);
  const unblock = await fetch(`${base}/api/admin/blocks/${(await blocked.json()).id}`, { method: 'DELETE', headers: { Cookie: session, 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(unblock.status, 200);
} finally {
  await new Promise(resolve => server.close(resolve));
  rmSync(dir, { recursive: true, force: true });
}
console.log('Booking API: autenticação, disponibilidade, concorrência, duração, bloqueio e persistência OK');
